#!/usr/bin/env python3
"""
The dial registry: resolve the 8-character hash in a file name to the dial
definition that produced it.

Every SnowStorm output carries that hash, and re-deriving a file's parameters
needs the exact dial file it was made with. "Keep your dial file forever" is
fine advice for one person and useless for a collaboration, so the definitions
live here, versioned, and this resolves a hash to one of them.

Adding a model means adding a JSON file to dials/ and never editing it again:
edit it and the hash changes, which by design makes it a different model. If
you want a variant, add a new file.

Usage:
  snowstorm_dials.py --list
  snowstorm_dials.py --resolve e1d55d70
  snowstorm_dials.py --index > dials/INDEX.md
"""

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from snowstorm_params import dial_hash  # noqa: E402

REGISTRY = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "dials")


def registry():
    out = {}
    for name in sorted(os.listdir(REGISTRY)):
        if not name.endswith(".json"):
            continue
        path = os.path.join(REGISTRY, name)
        try:
            dials = json.load(open(path))
        except json.JSONDecodeError as e:
            print(f"warning: {name} is not valid JSON ({e})", file=sys.stderr)
            continue
        out[dial_hash(dials)] = (name, dials)
    return out


def main():
    p = argparse.ArgumentParser()
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--list", action="store_true")
    g.add_argument("--resolve", metavar="HASH")
    g.add_argument("--index", action="store_true", help="emit INDEX.md")
    args = p.parse_args()

    reg = registry()

    if args.list:
        for h, (name, dials) in reg.items():
            print(f"{h}  {name:40s} {len(dials)} dials: {', '.join(sorted(dials))}")
        return 0

    if args.resolve:
        hit = reg.get(args.resolve)
        if not hit:
            print(f"no dial definition with hash {args.resolve} in {REGISTRY}.\n"
                  "If the file came from outside this repository, get the dial file from "
                  "whoever produced it -- the values cannot be re-derived without it.",
                  file=sys.stderr)
            return 1
        name, dials = hit
        print(f"# {name}", file=sys.stderr)
        json.dump(dials, sys.stdout, indent=2)
        sys.stdout.write("\n")
        return 0

    if args.index:
        print("# Dial registry\n")
        print("Generated by `bin/snowstorm_dials.py --index`. The hash is what appears in")
        print("output file names; it is the fingerprint of the file's exact contents, so")
        print("**never edit a file listed here** -- add a new one.\n")
        print("| hash | file | dials |")
        print("|---|---|---|")
        for h, (name, dials) in reg.items():
            print(f"| `{h}` | [{name}]({name}) | {', '.join(sorted(dials))} |")
        return 0


if __name__ == "__main__":
    sys.exit(main())
